// Helper to generate initial telemetry history points
const generateHistory = (baseVal: number, variance: number, points = 12) => {
  const result = [];
  const now = new Date();
  for (let i = points - 1; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 5 * 60 * 1000);
    const jitter = (Math.random() - 0.5) * variance;
    result.push({
      timestamp: time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
      val: Number((baseVal + jitter).toFixed(2)),
    });
  }
  return result;
};

